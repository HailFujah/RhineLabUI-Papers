import assert from "node:assert/strict";
import { ArchiveWheel } from "../src/archive-wheel.ts";
const wheel = new ArchiveWheel();
let time = 0;
const move = (changes, papers = true, gap = 20) => wheel.move({ deltaX: 0, deltaY: 0, deltaMode: 0, shiftKey: false, ctrlKey: false, ...changes }, papers, 800, time += gap);
assert.deepEqual(move({ deltaX: 120 }), { axis: "lane", direction: 1, steps: 1 });
assert.deepEqual(move({ deltaY: 100 }), { axis: "lane", direction: 1, steps: 1 });
assert.deepEqual(move({ deltaY: -100 }), { axis: "lane", direction: -1, steps: 1 });
move({ deltaY: 90 });
assert.deepEqual(move({ deltaY: 20, shiftKey: true }), { axis: "row", direction: 1, steps: 0 });
assert.deepEqual(move({ deltaX: 80, shiftKey: true }), { axis: "row", direction: 1, steps: 1 });
move({ deltaY: 90 });
assert.equal(move({ deltaY: 20 }, true, 200).steps, 0, "Old gestures cannot contribute leftover deltas");
assert.equal(move({ deltaY: 3, deltaMode: 1 }).steps, 1);
assert.equal(move({ deltaY: 1, deltaMode: 2 }).steps, 3);
assert.equal(move({ deltaY: 100, ctrlKey: true }), null, "Browser pinch zoom remains native");
assert.equal(move({ deltaX: 100 }, false), null, "Original archives retain their wheel behavior");
assert.deepEqual(move({ deltaY: 100 }, false), { axis: "row", direction: 1, steps: 1 });
move({ deltaY: 90 }, false);
assert.equal(move({ deltaY: 20 }).steps, 0, "Library switches clear the accumulator");
wheel.reset();
assert.equal(move({ deltaX: 80 }).steps, 0);
console.log("Paper horizontal wheel, Shift categories, units, reversal, reset and archive regression passed.");
